import assert from 'node:assert/strict';
import {handleAuth} from '../worker/auth.mjs';
const origin='https://nyducati.hidden-silence-47e4.workers.dev';
const env={GITHUB_CLIENT_ID:'test-id',GITHUB_CLIENT_SECRET:'test-secret'};
assert.equal((await handleAuth(new Request(origin+'/auth?provider=github'),{})).status,503);
assert.equal((await handleAuth(new Request('https://evil.example/auth?provider=github'),env)).status,400);
const start=await handleAuth(new Request(origin+'/auth?provider=github'),env);
assert.equal(start.status,302);
const target=new URL(start.headers.get('location'));
assert.equal(target.origin,'https://github.com');assert.equal(target.searchParams.get('redirect_uri'),origin+'/auth/callback');
assert.equal(target.searchParams.get('code_challenge_method'),'S256');
const cookie=start.headers.get('set-cookie').split(';')[0];
const callback=origin+'/auth/callback?code=fake&state='+target.searchParams.get('state');
let calls=0;
const mock=async(url,options)=>{calls++;if(url.includes('access_token')){assert.equal(JSON.parse(options.body).client_secret,'test-secret');return Response.json({access_token:'fake-token'});}return Response.json({permissions:{push:true}});};
assert.equal((await handleAuth(new Request(callback),env,mock)).status,400);
assert.equal((await handleAuth(new Request(callback.replace('state=','state=wrong'),{headers:{Cookie:cookie}}),env,mock)).status,400);
assert.equal(calls,0);
const success=await handleAuth(new Request(callback,{headers:{Cookie:cookie}}),env,mock);
assert.equal(success.status,200);const html=await success.text();assert.ok(html.includes('authorization:github:success:'));assert.ok(html.includes('event.source!==window.opener'));assert.ok(!html.includes('test-secret'));assert.ok(success.headers.get('set-cookie').includes('Max-Age=0'));
assert.equal((await handleAuth(new Request(callback,{headers:{Cookie:cookie}}),env,async url=>url.includes('access_token')?Response.json({access_token:'fake'}):Response.json({permissions:{push:false}}))).status,403);
console.log('PASS: OAuth redirect/PKCE, session checks, repository permission, popup origin/source checks, secret isolation.');
